"""Unit tests for pipeline/check_provenance.py (no Blender).

    cd artifacts/exercise-visual-system && python3 -m unittest discover -s tests -v

The checker itself is loaded from its file path (pipeline/ has no package)
and exercised against temporary kit trees: a good tree must pass, and each
kind of violation must be reported. The fixture strings below deliberately
name banned sources so the blocklist is proven to catch them; this file is
on the checker's ALLOWLIST for exactly that reason.
"""

from __future__ import annotations

import importlib.util
import json
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location(
    "check_provenance", ROOT / "pipeline" / "check_provenance.py")
assert _spec is not None and _spec.loader is not None
check_provenance = importlib.util.module_from_spec(_spec)
sys.modules["check_provenance"] = check_provenance
_spec.loader.exec_module(check_provenance)

GOOD_EXERCISE = {
    "motion_provenance": [
        {"what": "motion", "source": "motionlab/families/squat.py (this repository)",
         "license": "original work of this repository"},
        {"what": "angles", "source": "Schoenfeld 2010", "license": "facts"},
    ],
    "motion_source_id": "motionlab_test_v1",
    "motion_source_type": "PROCEDURAL_TEMPLATE",
    "motion_source_license": "Generated by motionlab (this repository).",
}


def _make_kit(tmp: Path, exercise: dict | None = GOOD_EXERCISE) -> Path:
    kit = tmp / "kit"
    exercise_dir = kit / "test-exercise"
    exercise_dir.mkdir(parents=True)
    if exercise is not None:
        (exercise_dir / "exercise.json").write_text(json.dumps(exercise), encoding="utf-8")
    return kit


class ProvenanceTests(unittest.TestCase):
    def test_good_tree_passes(self):
        with tempfile.TemporaryDirectory() as tmp:
            kit = _make_kit(Path(tmp))
            self.assertEqual(check_provenance.check(kit), [])

    def test_no_exercise_found_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            kit = Path(tmp) / "kit"
            kit.mkdir()
            violations = check_provenance.check(kit)
            self.assertEqual(len(violations), 1)
            self.assertIn("không tìm thấy exercise.json", violations[0])

    def test_missing_provenance_fails(self):
        exercise = dict(GOOD_EXERCISE)
        del exercise["motion_provenance"]
        with tempfile.TemporaryDirectory() as tmp:
            violations = check_provenance.check(_make_kit(Path(tmp), exercise))
            self.assertTrue(any("motion_provenance" in v for v in violations))

    def test_empty_provenance_list_fails(self):
        exercise = dict(GOOD_EXERCISE, motion_provenance=[])
        with tempfile.TemporaryDirectory() as tmp:
            violations = check_provenance.check(_make_kit(Path(tmp), exercise))
            self.assertTrue(any("motion_provenance" in v for v in violations))

    def test_provenance_entry_missing_license_fails(self):
        exercise = dict(GOOD_EXERCISE)
        exercise["motion_provenance"] = [{"what": "motion", "source": "somewhere"}]
        with tempfile.TemporaryDirectory() as tmp:
            violations = check_provenance.check(_make_kit(Path(tmp), exercise))
            self.assertTrue(any("license" in v for v in violations))

    def test_missing_source_field_fails(self):
        exercise = dict(GOOD_EXERCISE)
        del exercise["motion_source_license"]
        with tempfile.TemporaryDirectory() as tmp:
            violations = check_provenance.check(_make_kit(Path(tmp), exercise))
            self.assertTrue(any("motion_source_license" in v for v in violations))

    def test_invalid_json_fails_without_crashing(self):
        with tempfile.TemporaryDirectory() as tmp:
            kit = _make_kit(Path(tmp), exercise=None)
            (kit / "test-exercise" / "exercise.json").write_text("{broken", encoding="utf-8")
            violations = check_provenance.check(kit)
            self.assertTrue(any("không đọc được JSON" in v for v in violations))

    def test_banned_token_in_source_file_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            kit = _make_kit(Path(tmp))
            (kit / "notes.py").write_text("# retarget from Mixamo clip\n", encoding="utf-8")
            violations = check_provenance.check(kit)
            self.assertTrue(any("mixamo" in v for v in violations))

    def test_banned_token_in_provenance_text_fails(self):
        exercise = dict(GOOD_EXERCISE)
        exercise["motion_provenance"] = [
            {"what": "motion", "source": "CMU mocap database", "license": "unknown"}]
        with tempfile.TemporaryDirectory() as tmp:
            violations = check_provenance.check(_make_kit(Path(tmp), exercise))
            self.assertTrue(any("cmu" in v or "mocap" in v for v in violations))

    def test_banned_motion_format_fails(self):
        with tempfile.TemporaryDirectory() as tmp:
            kit = _make_kit(Path(tmp))
            (kit / "test-exercise" / "clip.bvh").write_bytes(b"HIERARCHY\n")
            violations = check_provenance.check(kit)
            self.assertTrue(any(".bvh" in v for v in violations))

    def test_allowlisted_file_with_token_passes(self):
        # The checker's own file is on the ALLOWLIST: a temp tree shaped like
        # the real one must pass even though the file names banned sources.
        with tempfile.TemporaryDirectory() as tmp:
            kit = _make_kit(Path(tmp))
            pipeline = kit / "pipeline"
            pipeline.mkdir()
            (pipeline / "check_provenance.py").write_text(
                "# mentions Mixamo, CMU, Carnegie Mellon, mocap\n", encoding="utf-8")
            self.assertEqual(check_provenance.check(kit), [])

    def test_real_tree_passes(self):
        # The committed kit must pass: the gate is green on the current tree.
        self.assertEqual(check_provenance.check(ROOT), [])


if __name__ == "__main__":
    unittest.main()
